from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    JSON,
    String,
    Table,
    UniqueConstraint,
    false,
)

from core.db import metadata


floor_readings = Table('floor_readings', metadata,
    Column('code', String(64), primary_key=True),
    Column('panel', String(160), ForeignKey('studio_panels.code'), nullable=False),
    Column('survey', String(160), nullable=False),
    Column('x_cm', Integer, nullable=False),
    Column('y_cm', Integer, nullable=False),
    # 领点记录在交读前没有滑步值；正式读数由服务层校验非空和范围。
    Column('slide', Float, nullable=True),
    Column('capture_key', String(255), nullable=False, index=True),
    Column('checked', Boolean, nullable=False, server_default=false()),
    Column('status', String(32), nullable=False, server_default='recorded'),
    Column('source', String(32), nullable=True),
    Column('client_key', String(160), nullable=True, unique=True),
    Column('claimed_by', String(160), nullable=True),
    Column('reviewed_by', String(160), nullable=True),
    Column('group_name', String(160), nullable=True),
    Column('disputed', Boolean, nullable=False, server_default=false()),
    Column('conflict_code', String(64), nullable=True, index=True),
    Column('created_at', DateTime, nullable=True),
    CheckConstraint('slide IS NULL OR slide BETWEEN 0 AND 1'),
    CheckConstraint('x_cm >= 0'),
    CheckConstraint('y_cm >= 0'),
)


point_claims = Table('point_claims', metadata,
    Column('code', String(64), primary_key=True),
    Column('panel', String(160), ForeignKey('studio_panels.code'), nullable=False),
    Column('survey', String(160), nullable=False),
    Column('x_cm', Integer, nullable=False),
    Column('y_cm', Integer, nullable=False),
    Column('spacing_cm', Integer, nullable=False, server_default='20'),
    Column('status', String(32), nullable=False, server_default='claimed'),
    Column('claimed_by', String(160), nullable=True),
    Column('client_key', String(160), nullable=True, unique=True),
    Column('grouping_code', String(64), nullable=True),
    Column('group_a', String(160), nullable=True),
    Column('point_a', String(64), nullable=True),
    Column('group_b', String(160), nullable=True),
    Column('point_b', String(64), nullable=True),
    Column('midpoint_x', Float, nullable=True),
    Column('midpoint_y', Float, nullable=True),
    Column('pair_distance_cm', Float, nullable=True),
    Column('reading_code', String(64), nullable=True),
    Column('created_at', DateTime, nullable=True),
    UniqueConstraint('panel', 'survey', 'x_cm', 'y_cm', name='uq_point_claims_panel_survey_xy'),
    CheckConstraint('spacing_cm > 0'),
)


reading_conflicts = Table('reading_conflicts', metadata,
    Column('code', String(64), primary_key=True),
    Column('panel', String(160), ForeignKey('studio_panels.code'), nullable=False),
    Column('survey', String(160), nullable=False),
    Column('x_cm', Integer, nullable=False),
    Column('y_cm', Integer, nullable=False),
    Column('location_key', String(255), nullable=False, index=True),
    Column('candidate_codes', JSON, nullable=False),
    Column('live_code', String(64), nullable=True),
    Column('offline_code', String(64), nullable=True),
    Column('status', String(32), nullable=False, server_default='pending'),
    Column('selected_code', String(64), nullable=True),
    Column('resolved_by', String(160), nullable=True),
    Column('resolution_note', String(255), nullable=True),
    Column('active_key', String(255), nullable=True, unique=True),
    Column('created_at', DateTime, nullable=True),
    Column('resolved_at', DateTime, nullable=True),
)
